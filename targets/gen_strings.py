"""Generate crackme1_strings.h: messages XOR'd with a rolling key (0x33 + 7*i)
so `strings` on the binary reveals nothing useful."""
MSGS = {
    "E_USAGE": "usage: crackme1 <name> <serial XXXX-XXXX>",
    "E_OK": "Serial accepted. Welcome, %s!\n",
    "E_BAD": "Invalid serial.",
}
out = ["// generated by gen_strings.py -- do not edit", "#pragma once"]
for name, s in MSGS.items():
    enc = [b ^ ((0x33 + 7 * i) & 0xFF) for i, b in enumerate(s.encode())]
    out.append(f"static const unsigned char {name}[{len(enc)}] = {{{', '.join(hex(b) for b in enc)}}};")
open(__file__.replace("gen_strings.py", "crackme1_strings.h"), "w").write("\n".join(out) + "\n")
print("wrote crackme1_strings.h")
