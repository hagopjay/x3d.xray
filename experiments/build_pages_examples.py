#!/usr/bin/env python3
"""Build the static Examples page for GitHub Pages: docs/demos/eda-examples/v1/index.html.

Each example under examples/ is run here (offline, synthetic, seeded, no clock) and its printed output is embedded next
to its source, so the page shows what the code printed when the page was built. Nothing is typed in by hand: re-run this
script and the page changes only if an example's output changes. Example 3 needs Node (it runs the page's own tools.js).

  python3 experiments/build_pages_examples.py --out docs/demos/eda-examples/v1
"""
from __future__ import annotations

import argparse
import html
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

EXAMPLES = [
    ("eda_1_signal_and_noise.py", "1. Signal and noise",
     "What does a Confirmed grade mean, and how often does pure noise earn one?",
     "Two runs. In the first a difference is planted and the exploratory stage finds it. In the second nothing is planted, "
     "six seeds are tried, and one of them still earns a Confirmed. That is the honest rate, and the page says it."),
    ("eda_2_simpsons_paradox.py", "2. Simpson's paradox",
     "What happens when a difference between two kinds of author is really a difference between repos?",
     "The groups differ a lot and q is tiny, yet nothing is Confirmed, because no repo holds both groups. "
     "The grade refuses to turn a between-repo difference into a claim about authors."),
    ("eda_3_the_price_of_looking.py", "3. The price of looking",
     "Why is the same answer worth less when it is the fortieth look than when it is the thirteenth?",
     "The same p, nine different q. Every look you take is added to the family the correction counts over. "
     "This one runs the page's own JavaScript, so it is also the check that the browser and the Python agree."),
]


def run(example: str) -> str:
    done = subprocess.run([sys.executable, str(ROOT / "examples" / example)], cwd=ROOT,
                          capture_output=True, text=True, timeout=300)
    if done.returncode != 0:
        raise SystemExit(f"{example} failed ({done.returncode}):\n{done.stderr[-2000:]}")
    return done.stdout.rstrip("\n")


CSS = """
:root{--bg:#fafaf7;--fg:#1b1d21;--mute:#5b6270;--card:#fff;--line:#d9dce2;--acc:#0b6bcb;--code:#f1f2f5}
@media (prefers-color-scheme:dark){:root{--bg:#101215;--fg:#e6e8ec;--mute:#9aa3b2;--card:#171a1f;--line:#2b3038;--acc:#6db3ff;--code:#0c0e11}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.55 system-ui,-apple-system,Segoe UI,sans-serif}
main{max-width:60rem;margin:0 auto;padding:2rem 1rem 4rem}
h1{font-size:1.9rem;margin:.2rem 0 .4rem}h2{font-size:1.3rem;margin:0 0 .3rem}
a{color:var(--acc)}p.lede{color:var(--mute);margin:.2rem 0 1.4rem}
section.ex{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:1.1rem 1.2rem;margin:1.2rem 0}
.q{font-weight:600;margin:.1rem 0 .4rem}.why{color:var(--mute);margin:.2rem 0 .8rem}
pre{background:var(--code);border:1px solid var(--line);border-radius:8px;padding:.8rem;overflow:auto;font:13px/1.45 ui-monospace,Menlo,Consolas,monospace;margin:.4rem 0}
details{margin-top:.6rem}summary{cursor:pointer;color:var(--acc)}
nav{font-size:.92rem;margin-bottom:1rem}small{color:var(--mute)}
"""


def page(blocks: list[str]) -> str:
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>x3d.xray examples</title>
<meta name="description" content="Three runnable explanations of what the exploratory stage claims and what it does not. Synthetic data only.">
<style>{CSS}</style></head><body><main>
<nav><a href="../../../">x3d.xray demos</a> · <a href="https://github.com/hagopjay/x3d.xray/tree/main/examples">source on GitHub</a></nav>
<h1>Three examples of the exploratory stage</h1>
<p class="lede">Each one runs offline on synthetic data (seeded, no clock, no network). What is printed below is what the code printed
when this page was built, and CI runs the same three files as tests, so the page cannot drift from the code. Every number here comes from the
exact-integer EDA kernel in <code>x3dray/eda.py</code> (and, for example 3, its JavaScript twin in <code>x3dray/web/tools.js</code>).</p>
{''.join(blocks)}
<p><small>Generated by <code>experiments/build_pages_examples.py</code>. Synthetic data only; no private repository harvest is included.</small></p>
</main></body></html>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()
    blocks = []
    for fname, title, question, note in EXAMPLES:
        out = run(fname)
        src = (ROOT / "examples" / fname).read_text(encoding="utf-8")
        blocks.append(
            f'<section class="ex" id="{fname.split("_")[1]}"><h2>{html.escape(title)}</h2>'
            f'<p class="q">{html.escape(question)}</p><p class="why">{html.escape(note)}</p>'
            f'<pre>{html.escape(out)}</pre>'
            f'<details><summary>Show the source ({html.escape(fname)})</summary><pre>{html.escape(src)}</pre></details></section>')
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "index.html").write_text(page(blocks), encoding="utf-8")
    print(f"wrote {args.out / 'index.html'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
